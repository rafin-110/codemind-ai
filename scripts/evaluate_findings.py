"""Phase 3 evaluation: run the whole agent loop once per finding on the synthetic sample.

For every finding: fresh orchestrator → load sample → analyse → ask for a fix →
approve every proposal the critic accepts (this script plays the human) → record
the outcome. Also scores detection against samples/EXPECTED_FINDINGS.json.
Nothing is mocked; each validation is a real pytest run on a working copy.

    python scripts/evaluate_findings.py
Writes docs/test-evidence/phase3_fix_evaluation.{json,md}.
"""

from __future__ import annotations

import json
import platform
import shutil
import sys
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from codemind.models import WorkflowState as S  # noqa: E402
from codemind.orchestrator.orchestrator import Orchestrator  # noqa: E402

OUT = ROOT / "docs" / "test-evidence"
sys.stdout.reconfigure(encoding="utf-8", errors="replace")


def detection_score(findings) -> dict:
    expected = json.loads((ROOT / "samples" / "EXPECTED_FINDINGS.json").read_text(encoding="utf-8"))
    items = expected["expected"]
    want = {(e["rule_id"], e["file"], e["line"]) for e in items}
    got = {(f.rule_id, f.file, f.line) for f in findings}
    tp = len(want & got)
    return {"expected": len(want), "reported": len(got), "true_positives": tp,
            "missed": sorted(map(list, want - got)), "extra": sorted(map(list, got - want)),
            "precision": round(tp / len(got), 3) if got else None,
            "recall": round(tp / len(want), 3) if want else None}


def run_one(root: Path, fid: str) -> dict:
    o = Orchestrator(workspace_root=root)
    o.load_sample()
    o.analyze()
    f = o.ctx.finding(fid)
    row = {"finding": fid, "rule": f.rule_id, "severity": f.severity.value, "confidence": f.confidence.value,
           "title": f.title.replace("`", ""), "attempts": [], "final_state": None, "original_unchanged": None}
    start = time.perf_counter()
    o.select_finding(fid)
    while o.ctx.state is S.AWAITING_APPROVAL:
        p = o.ctx.current_proposal
        o.approve(p.patch_id, p.patch_hash, "evaluation script approval")
        v = o.ctx.latest_validation
        row["attempts"].append({"strategy": p.strategy_name, "status": v.status.value,
                                "tests": f"{v.tests_passed} passed / {v.tests_failed} failed / {v.tests_errors} errors",
                                "failing_tests": sorted(c.name for c in v.test_cases if c.outcome in ("failed", "error"))})
        row["original_unchanged"] = v.original_unchanged
    row["final_state"] = o.ctx.state.value
    row["note"] = o.ctx.blocked_reason or (o.ctx.decisions[-1].reason if o.ctx.decisions else "")
    row["seconds"] = round(time.perf_counter() - start, 2)
    return row


def main() -> int:
    tmp = Path(tempfile.mkdtemp(prefix="codemind_eval_"))
    try:
        t0 = time.perf_counter()
        o = Orchestrator(workspace_root=tmp / "probe")
        o.load_sample()
        o.analyze()
        analysis_s = round(time.perf_counter() - t0, 2)
        ids = [f.id for f in o.ctx.findings]
        score = detection_score(o.ctx.findings)
        rows = [run_one(tmp / fid, fid) for fid in ids]
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    result = {"generated": time.strftime("%Y-%m-%d %H:%M:%S %z"), "python": platform.python_version(),
              "os": platform.platform(), "analysis_seconds_incl_baseline_tests": analysis_s,
              "detection": score, "fixes": rows}
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "phase3_fix_evaluation.json").write_text(json.dumps(result, indent=2), encoding="utf-8")

    validated = sum(r["final_state"] == "VALIDATED" for r in rows)
    first_try = sum(r["final_state"] == "VALIDATED" and len(r["attempts"]) == 1 for r in rows)
    lines = ["# Phase 3 fix evaluation (generated by `scripts/evaluate_findings.py`)", "",
             f"- Run: {result['generated']} · Python {result['python']} · {result['os']}",
             f"- Analysis of the sample incl. baseline test run: {analysis_s}s",
             f"- Detection vs `samples/EXPECTED_FINDINGS.json`: {score['true_positives']}/{score['expected']} planted "
             f"issues found at the exact rule + file + line, {len(score['extra'])} extra, "
             f"precision {score['precision']}, recall {score['recall']}",
             f"- Fixes: {validated}/{len(rows)} findings reached VALIDATED "
             f"({first_try} on the first strategy); every original re-hashed unchanged: "
             f"{all(r['original_unchanged'] in (True, None) for r in rows)}", "",
             "| Finding | Rule | Severity | Attempts (strategy → result) | Final state | Note |",
             "|---|---|---|---|---|---|"]
    for r in rows:
        att = "<br>".join(f"{a['strategy']} → {a['status']} ({a['tests']})" for a in r["attempts"]) or "none"
        lines.append(f"| {r['finding']} {r['title']} | {r['rule']} | {r['severity']} | {att} | "
                     f"{r['final_state']} | {r['note'][:140].replace('|', '/')} |")
    pre = sorted({t for r in rows for a in r["attempts"] if a["status"] == "Passed" for t in a["failing_tests"]})
    lines += ["", f"Tests still failing inside a Passed validation: {', '.join(pre) or 'none'}. "
              "They already fail on the untouched original (baseline) and belong to F-004, so the pass rule "
              "lists them as pre-existing instead of blaming the patch. They pass once F-004 is fixed.",
              "", "The script approves every proposal itself to measure the agents. In the app a human makes "
              "each decision. Passing tests do not prove the code is bug-free."]
    (OUT / "phase3_fix_evaluation.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""Optional local Ollama adapter (free, offline). Falls back to the input text on any problem."""

from __future__ import annotations

import json
import urllib.error
import urllib.request

from codemind import config
from codemind.llm.adapter import LLMAdapter, LLMText

_FORBIDDEN = ("```", "approve", "approved", "def ", "import ")


class OllamaLLM(LLMAdapter):
    def __init__(self, url: str = config.OLLAMA_URL, model: str = config.OLLAMA_MODEL,
                 timeout: float = config.OLLAMA_TIMEOUT_S) -> None:
        self.url, self.model, self.timeout = url.rstrip("/"), model, timeout
        self.label = f"Ollama ({model}) - wording only, labelled in the UI"
        # Ollama is local: never route it through a system HTTP proxy
        self._opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))

    def _post(self, path: str, payload: dict) -> dict:
        req = urllib.request.Request(self.url + path, data=json.dumps(payload).encode(),
                                     headers={"Content-Type": "application/json"})
        with self._opener.open(req, timeout=self.timeout) as resp:  # noqa: S310 - fixed local URL
            return json.loads(resp.read(1_000_000))

    def available(self) -> bool:
        try:
            req = urllib.request.Request(self.url + "/api/tags")
            with self._opener.open(req, timeout=3) as resp:  # noqa: S310
                return resp.status == 200
        except (OSError, urllib.error.URLError, ValueError):
            return False

    def rephrase(self, text: str, context: str = "") -> LLMText:
        prompt = ("Rewrite this explanation for a beginner programmer in at most two sentences. "
                  "Keep every technical fact. Do not add code.\n"
                  f"Topic: {context}\nExplanation: {text}")
        try:
            data = self._post("/api/generate", {"model": self.model, "prompt": prompt, "stream": False})
        except (OSError, urllib.error.URLError, ValueError, json.JSONDecodeError) as exc:
            return LLMText(text, "deterministic", f"LLM unavailable ({type(exc).__name__}); deterministic text shown")
        out = str(data.get("response", "")).strip() if isinstance(data, dict) else ""
        if not out or len(out) > 600 or any(tok in out.lower() for tok in _FORBIDDEN):
            return LLMText(text, "deterministic", "LLM output failed validation; deterministic text shown")
        return LLMText(out, f"llm:{self.model}", "generated by a local model; facts come from the deterministic rule")
